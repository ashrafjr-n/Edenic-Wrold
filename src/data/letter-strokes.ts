/** The two writing lines drawn under a letter on the trace board: the
    dashed one the letter's body starts from, and the solid baseline it sits
    on. Descenders hang below the baseline — that is the lesson. */
export interface LetterGuide {
  top: number;
  base: number;
}

const CAPITAL_GUIDE: LetterGuide = { top: 14, base: 86 };
const X_HEIGHT: LetterGuide = { top: 34, base: 86 };
const ASCENDER: LetterGuide = { top: 42, base: 88 };
const DESCENDER: LetterGuide = { top: 14, base: 64 };

const SMALL_GUIDE: Partial<Record<LetterId, LetterGuide>> = {
  b: ASCENDER, d: ASCENDER, f: ASCENDER, h: ASCENDER, k: ASCENDER, l: ASCENDER, t: ASCENDER,
  g: DESCENDER, p: DESCENDER, q: DESCENDER, y: DESCENDER,
  i: { top: 38, base: 86 },
  j: { top: 30, base: 72 },
};

export function letterGuide(id: LetterId, capital: boolean): LetterGuide {
  if (capital) return CAPITAL_GUIDE;
  return SMALL_GUIDE[id] ?? X_HEIGHT;
}
